pub fn find_tool(id: &str) -> Option<Tool> {
    all_tools().into_iter().find(|t| t.id.eq_ignore_ascii_case(id))
}

pub fn tools_by_category(category: Category) -> Vec<Tool> {
    all_tools().into_iter().filter(|t| t.category == category).collect()
}
